import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)

// Bootstrap executed inside the browser worker. The UMD builds concatenated
// before it define the `wasmUtil`, `emnapi` and `emnapiCore` globals. The
// worker gets the compiled WebAssembly.Module and shared memory posted by the
// main thread (emnapi 'load' message), so it needs no wasm bytes of its own.
const bootstrap = `
(function () {
  'use strict';
  var handler = new emnapiCore.MessageHandler({
    onLoad: function (data) {
      var wasi = new wasmUtil.WASI({ version: 'preview1' });
      return emnapiCore.instantiateNapiModuleSync(data.wasmModule, {
        childThread: true,
        wasi: wasi,
        context: emnapi.getDefaultContext(),
        overwriteImports: function (importObject) {
          importObject.env = Object.assign(
            {},
            importObject.env,
            importObject.napi,
            importObject.emnapi,
            { memory: data.wasmMemory }
          );
          return importObject;
        }
      });
    }
  });
  self.onmessage = function (e) { handler.handle(e); };
})();
`

/**
 * Concatenates the UMD builds of the emnapi runtime stack with the bootstrap
 * above into a single self-contained classic-worker script, exported as a
 * string so browser bundles can spawn wasm threads from a Blob URL without
 * any bundler-specific worker support.
 */
export function buildWorkerBundle (outputFile) {
  // The dist files aren't in the packages' `exports` maps, so resolve each
  // package root from its entry point and join manually.
  const distFile = (name, rel) => {
    const marker = path.join('node_modules', ...name.split('/'))
    const entry = require.resolve(name)
    const root = entry.slice(0, entry.indexOf(marker) + marker.length)
    return path.join(root, rel)
  }

  const parts = [
    distFile('@tybys/wasm-util', 'dist/wasm-util.min.js'),
    distFile('@emnapi/runtime', 'dist/emnapi.min.js'),
    distFile('@emnapi/core', 'dist/emnapi-core.min.js')
  ].map((file) => fs.readFileSync(file, 'utf8'))

  const source = parts.join(';\n') + ';\n' + bootstrap

  fs.mkdirSync(path.dirname(outputFile), { recursive: true })
  fs.writeFileSync(
    outputFile,
    '// Generated by utils/buildWorkerBundle.mjs — self-contained browser worker\n' +
    '// for wasm threads (spawned from a Blob URL by wasmCreation.cjs).\n' +
    // JSDoc cast: widen to `string` so tsc's .d.cts doesn't embed the
    // whole worker source as a literal type.
    '/** @type {string} */\n' +
    `const source = ${JSON.stringify(source)};\n` +
    'module.exports = { source };\n'
  )
  console.log(`Successfully built worker bundle: ${outputFile}`)
}
